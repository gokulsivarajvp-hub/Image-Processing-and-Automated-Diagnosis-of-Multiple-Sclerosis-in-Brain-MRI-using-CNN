def load_dataset(image_dir, mask_dir, image_size=(256, 256)):
    X, y, orig_images = [], [], []

    image_files = sorted([f for f in os.listdir(image_dir) if f.endswith(('.png', '.jpg'))])

    for img_file in image_files:
        img_path = os.path.join(image_dir, img_file)
        base_name = os.path.splitext(img_file)[0]
        mask_file = base_name + '_lesion_mask_mask.png'
        mask_path = os.path.join(mask_dir, mask_file)

        if not os.path.exists(mask_path):
            continue

        img_orig = cv2.imread(img_path, cv2.IMREAD_GRAYSCALE)
        orig_images.append(img_orig.copy())

        img = cv2.resize(img_orig, image_size) / 255.0
        img = np.expand_dims(img, axis=-1)

        mask = cv2.imread(mask_path, cv2.IMREAD_GRAYSCALE)
        mask = cv2.resize(mask, image_size)
        mask = (mask > 127).astype(np.uint8)
        mask = np.expand_dims(mask, axis=-1)

        X.append(img)
        y.append(mask)

    return np.array(X), np.array(y), orig_images

