def detect_lesions(image):
    # Normalize
    norm_image = cv2.normalize(image, None, 0, 255, cv2.NORM_MINMAX)
    # Blur
    blurred = cv2.GaussianBlur(norm_image, (5, 5), 0)
    # Threshold bright areas
    threshold_value = np.percentile(blurred, 98)
    bright_mask = (blurred >= threshold_value).astype(np.uint8) * 255
    # Clean with morphology
    kernel = np.ones((3, 3), np.uint8)
    bright_mask_clean = cv2.morphologyEx(bright_mask, cv2.MORPH_OPEN, kernel)
    # Connected components
    num_labels, labels, stats, _ = cv2.connectedComponentsWithStats(bright_mask_clean)
    lesion_mask = np.zeros_like(bright_mask_clean)
    for i in range(1, num_labels):
        if stats[i, cv2.CC_STAT_AREA] > 50:  # Filter small areas
            lesion_mask[labels == i] = 255
    return lesion_mask

