for i, idx in enumerate(indices):
    img = X_val[idx]
    original_img = orig_val[idx]
    h, w = original_img.shape

    # Enhance contrast
    clahe = cv2.createCLAHE(clipLimit=2.0, tileGridSize=(8, 8))
    enhanced_img = clahe.apply(original_img)

    # Predict from model
    pred_mask = model.predict(np.expand_dims(img, axis=0))[0]
    pred_mask = (pred_mask > 0.45).astype(np.uint8).squeeze()
    resized_pred = cv2.resize(pred_mask, (w, h), interpolation=cv2.INTER_NEAREST)

    # Extract central region
    cx1, cx2 = w // 4, 3 * w // 4
    cy1, cy2 = h // 4, 3 * h // 4
    central_crop = enhanced_img[cy1:cy2, cx1:cx2]

    # Adaptive threshold to detect localized bright spots
    central_thresh = cv2.adaptiveThreshold(central_crop, 255, cv2.ADAPTIVE_THRESH_MEAN_C,
                                           cv2.THRESH_BINARY, 15, -5)

    # Filter small uneven regions using connected components
    num_labels, labels, stats, _ = cv2.connectedComponentsWithStats(central_thresh)

    filtered_spots = np.zeros_like(central_thresh)
    for i in range(1, num_labels):
        area = stats[i, cv2.CC_STAT_AREA]
        if 10 <= area <= 150:  # Keeps small bright regions, removes large or noise
            filtered_spots[labels == i] = 255

    # Place filtered center spots back into full mask
    central_mask = np.zeros_like(resized_pred, dtype=np.uint8)
    central_mask[cy1:cy2, cx1:cx2] = filtered_spots

    # Combine with U-Net prediction
    final_mask = np.logical_or(resized_pred, (central_mask > 0)).astype(np.uint8)

    # Draw boxes on original image
    contours, _ = cv2.findContours(final_mask, cv2.RETR_EXTERNAL, cv2.CHAIN_APPROX_SIMPLE)
